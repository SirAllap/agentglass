#!/usr/bin/env bun
/*
 * The licences of what this build ships, for Settings › About.
 *
 * The direct runtime dependencies of web/ and server/ (what is compiled or
 * bundled into the app, not the tools that built it), each with the licence its
 * own package.json declares. Read from node_modules, so it is run where the
 * dependencies are installed and its output is committed:
 *
 *   bun run gen:licences
 *
 * A package that is not installed or declares no licence stops the run rather
 * than shipping a blank: a licence list with holes in it is worse than none.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..", "..");
const seen = new Map<string, { name: string; version: string; licence: string }>();
for (const dir of ["web", "server"]) {
  const pkg = JSON.parse(readFileSync(join(root, dir, "package.json"), "utf8")) as { dependencies?: Record<string, string> };
  for (const name of Object.keys(pkg.dependencies ?? {})) {
    const at = [join(root, dir, "node_modules", name), join(root, "node_modules", name)].find((p) => existsSync(join(p, "package.json")));
    if (!at) { console.error(`${name}: not installed (run bun install)`); process.exit(1); }
    const j = JSON.parse(readFileSync(join(at, "package.json"), "utf8")) as { version?: string; license?: string; licenses?: { type: string }[] };
    const licence = j.license ?? j.licenses?.map((l) => l.type).join(" OR ");
    if (!licence || !j.version) { console.error(`${name}: no licence or version in its package.json`); process.exit(1); }
    seen.set(name, { name, version: j.version, licence });
  }
}
const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const out = `// Generated by web/scripts/gen-licences.ts (bun run gen:licences). Do not edit.
// The direct runtime dependencies this build ships, with the licence each declares.

export interface Licence { name: string; version: string; licence: string }

export const LICENCES: readonly Licence[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(join(root, "web", "src", "lib", "licences.gen.ts"), out);
console.log(`wrote ${rows.length} licences`);
