// The theme file already on disk must repair itself (#339).
//
// #336 stopped GENERATING `set -g status-left "…"` / `set -g status-right "…"`,
// because those replace whatever the user had in those segments — a git
// branch, a battery, and in the case that found this, the
// `#(continuum_save.sh)` interpolation that is tmux-continuum's entire save
// timer. Overwriting it silently turned session persistence off: continuum
// kept reporting a 15-minute interval and had not saved for days.
//
// That fix only changed what is written. theme.tmux.conf is rewritten once per
// theme change, so anyone who ran agentglass before it still has the old file,
// sourced by every tmux server that opts in — so the bug comes back on the
// next new server, and the owner has no reason to suspect a file they have
// never opened. Confirmed on the machine where it was found: after installing
// the fixed build, the file still contained both lines, dated hours earlier.
import { describe, expect, test } from "bun:test";
import { repairTmuxTheme, tmuxTheme } from "../src/themesync.ts";

const OLD_FILE = `# Generated by agentglass — do not edit.
# Theme: Midnight Purple

set -g status-style "bg=#0f0a1a,fg=#d8b4fe"
set -g status-left-style "bg=#0f0a1a,fg=#a78bfa,bold"
set -g status-right-style "bg=#0f0a1a,fg=#c084fc"
set -g status-left "#[fg=#a78bfa,bold] #S "
set -g status-right "#[fg=#c084fc] %H:%M "
setw -g window-status-separator ""
set -g pane-active-border-style "fg=#a78bfa"
`;

describe("the destructive lines are removed", () => {
  test("both status segments go", () => {
    const out = repairTmuxTheme(OLD_FILE)!;
    expect(out).not.toContain(`set -g status-left "`);
    expect(out).not.toContain(`set -g status-right "`);
  });

  test("the -style lines stay — they colour a segment without owning it", () => {
    const out = repairTmuxTheme(OLD_FILE)!;
    expect(out).toContain(`set -g status-left-style "bg=#0f0a1a,fg=#a78bfa,bold"`);
    expect(out).toContain(`set -g status-right-style "bg=#0f0a1a,fg=#c084fc"`);
    expect(out).toContain(`set -g status-style "bg=#0f0a1a,fg=#d8b4fe"`);
  });

  test("everything else is left alone", () => {
    const out = repairTmuxTheme(OLD_FILE)!;
    expect(out).toContain(`setw -g window-status-separator ""`);
    expect(out).toContain(`set -g pane-active-border-style "fg=#a78bfa"`);
    expect(out).toContain("# Theme: Midnight Purple");
  });

  test("only two lines are dropped, not a block", () => {
    const before = OLD_FILE.split("\n").length;
    const after = repairTmuxTheme(OLD_FILE)!.split("\n").length;
    expect(before - after).toBe(2);
  });
});

describe("it knows when there is nothing to do", () => {
  test("a file the current generator wrote needs no repair", () => {
    const vars = {
      bg: "#0f0a1a", bg2: "#1a1333", bg3: "#2d1b4e", bg4: "#3f2766",
      text: "#f3e8ff", text2: "#e9d5ff", text3: "#d8b4fe", text4: "#c084fc",
      border: "#6d28d9", border2: "#7e22ce", primary: "#a78bfa", "primary-hover": "#c4b5fd",
      success: "#34d399", warning: "#fbbf24", error: "#f472b6", info: "#a78bfa",
      shadow: "rgba(0,0,0,.8)",
    } as any;
    expect(repairTmuxTheme(tmuxTheme(vars, "Midnight Purple"))).toBeNull();
  });

  test("null rather than an identical string, so the caller need not diff", () => {
    expect(repairTmuxTheme("set -g pane-border-lines single\n")).toBeNull();
  });
});

describe("the shapes tmux actually accepts", () => {
  // tmux takes `set-option` as the long form and `-g` is optional, so a file
  // written by an older release — or edited by hand — can carry any of these.
  for (const line of [
    `set -g status-left "#S"`,
    `set status-left "#S"`,
    `set-option -g status-right "%H:%M"`,
    `  set -g status-right "x"`,
    `set -g status-left '#S'`,
  ]) {
    test(`removes ${JSON.stringify(line)}`, () => {
      expect(repairTmuxTheme(`${line}\nset -g pane-border-lines single\n`)).not.toContain("status-");
    });
  }

  // The trap: a prefix match on "status-left" would eat the style lines too,
  // and those are ours and worth keeping. The quote is what tells them apart.
  for (const line of [
    `set -g status-left-style "bg=#000"`,
    `set -g status-left-length 30`,
    `set -g status-right-length 60`,
  ]) {
    test(`keeps ${JSON.stringify(line)}`, () => {
      expect(repairTmuxTheme(`${line}\n`)).toBeNull();
    });
  }
});

describe("what it protects", () => {
  test("a continuum save timer in status-right survives, because the line is dropped not rewritten", () => {
    // The repair removes agentglass's line entirely rather than replacing it,
    // so whatever the user's own rc sets afterwards is what ends up in effect.
    const file = `set -g status-right "#[fg=#c084fc] %H:%M "\n`;
    const out = repairTmuxTheme(file)!;
    expect(out.trim()).toBe("");
  });
});
