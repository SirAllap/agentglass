/*
 * xterm.js, compiled into a string the WebView can carry.
 *
 * A React Native WebView has no bundler and no network — the terminal document
 * is built in memory and handed over as HTML, and a strict page with a
 * `<script src>` in it would simply not load. So xterm and its addons are
 * bundled here into one IIFE and written out as a TypeScript module exporting
 * two strings, which `terminal-html.ts` inlines.
 *
 * Generated rather than committed by hand, and regenerated on `npm install`:
 * the alternative is a 400KB blob in the diff of every dependency bump, with
 * nobody able to tell whether it matches the version in package.json.
 *
 * `chrome74` because Android WebViews are not all current. The same reason the
 * shims below exist: esbuild lowers SYNTAX to the target and leaves runtime
 * APIs alone, so an old WebView parses the bundle fine and then throws on the
 * first `structuredClone` — which xterm calls while constructing a Terminal,
 * before anything is on screen.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import * as esbuild from "esbuild";

const require = createRequire(import.meta.url);
const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "src", "terminal", "engine.generated.ts");
const TARGET = "chrome74";
const PACKAGES = ["@xterm/xterm", "@xterm/addon-fit", "@xterm/addon-unicode11", "@xterm/addon-webgl"];

const version = async (name) => {
  const json = JSON.parse(await readFile(require.resolve(`${name}/package.json`), "utf8"));
  return `${name}@${json.version}`;
};

/** A `</script` inside a string would close the tag it is being embedded in. */
const safeFor = (value, tag) => value.replace(new RegExp(`</${tag}`, "gi"), `<\\/${tag}`);

async function buildJs() {
  const built = await esbuild.build({
    stdin: {
      contents: `
        import { Terminal } from '@xterm/xterm'
        import { FitAddon } from '@xterm/addon-fit'
        import { Unicode11Addon } from '@xterm/addon-unicode11'
        import { WebglAddon } from '@xterm/addon-webgl'

        // WeakRef (Chrome 84+): xterm constructs one lazily while tracking its
        // window. Holding a strong reference is fine for a single-document
        // terminal — nothing here outlives the page.
        if (typeof window.WeakRef === 'undefined') {
          window.WeakRef = function WeakRefShim(target) { this.__target = target }
          window.WeakRef.prototype.deref = function () { return this.__target }
        }

        // structuredClone (Chrome 98+): xterm clones its plain-data DEC-mode
        // defaults at construction. A JSON round-trip clones those correctly —
        // undefined-valued keys drop, and every reader treats absent as
        // undefined.
        if (typeof window.structuredClone === 'undefined') {
          window.structuredClone = function (value) { return JSON.parse(JSON.stringify(value)) }
        }

        // Element.replaceChildren (Chrome 86+): on the row-render path.
        if (typeof Element !== 'undefined' && !Element.prototype.replaceChildren) {
          Element.prototype.replaceChildren = function () {
            while (this.firstChild) this.removeChild(this.firstChild)
            this.append.apply(this, arguments)
          }
        }

        window.Terminal = Terminal
        window.FitAddon = FitAddon
        window.Unicode11Addon = Unicode11Addon
        window.WebglAddon = WebglAddon
      `,
      resolveDir: root,
      sourcefile: "terminal-engine-entry.js",
    },
    bundle: true,
    format: "iife",
    minify: true,
    platform: "browser",
    target: TARGET,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  return built.outputFiles[0].text;
}

const [js, rawCss, ...versions] = await Promise.all([
  buildJs(),
  readFile(require.resolve("@xterm/xterm/css/xterm.css"), "utf8"),
  ...PACKAGES.map(version),
]);

// Comments stripped so the inlined stylesheet is not mostly licence text.
const css = rawCss.replace(/\/\*[\s\S]*?\*\//g, "").trim();

await mkdir(path.dirname(out), { recursive: true });
await writeFile(out, [
  "// Generated by scripts/build-terminal-engine.mjs — do not edit by hand.",
  `// Packages: ${versions.join(", ")}.`,
  `// Target: ${TARGET}. Regenerate with \`npm run build:engine\`.`,
  "",
  `export const XTERM_JS = ${JSON.stringify(safeFor(js, "script"))};`,
  `export const XTERM_CSS = ${JSON.stringify(safeFor(css, "style"))};`,
  "",
].join("\n"));

console.log(`wrote ${path.relative(root, out)} — ${Math.round(js.length / 1024)}KB of engine`);
